def get_stats():
    """统计信息"""
    all_fields = set()
    field_counts = {}
    for doc_type, tpl in TEMPLATES.items():
        for f in tpl["fields"]:
            all_fields.add(f)
            field_counts[f] = field_counts.get(f, 0) + 1

    return {
        "doc_types": len(TEMPLATES),
        "unique_fields": len(all_fields),
        "total_field_slots": sum(len(t["fields"]) for t in TEMPLATES.values()),
        "top_fields": sorted(field_counts.items(), key=lambda x: -x[1])[:10],
    }


def get_fields_by_category():
    """按大类分组"""
    cats = {}
    for doc_type, tpl in TEMPLATES.items():
        cat = tpl["category"]
        if cat not in cats:
            cats[cat] = []
        cats[cat].append(doc_type)
    return cats


if __name__ == "__main__":
    stats = get_stats()
    print(f"文档类型: {stats['doc_types']} 种")
    print(f"唯一字段: {stats['unique_fields']} 个")
    print(f"字段总和: {stats['total_field_slots']} 个字段位")
    print(f"\n高频字段:")
    for f, c in stats['top_fields']:
        print(f"  {f}: {c} 种证件")
